    /// Returns true if pixel (px, py) within the glyph for ch is lit.
    /// px ∈ [0, CharW), py ∈ [0, CharH). Returns false for unmapped characters.
    public static bool IsLit(char ch, int px, int py)
    {
        ch = char.ToUpperInvariant(ch);
        if (!_glyphs.TryGetValue(ch, out var rows)) return false;
        return (rows[py] & (0b10000 >> px)) != 0;
    }

    public static bool HasGlyph(char ch) => _glyphs.ContainsKey(char.ToUpperInvariant(ch));
